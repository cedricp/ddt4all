def normalize(table):
    """Normalizes an addressing dict: keys and values upper-cased (str)."""
    out = {}
    for key, value in dict(table or {}).items():
        key = str(key).upper().strip()
        if key:
            out[key] = str(value).upper().strip()
    return out


def is_ext(can_id):
    """True if the CAN identifier is extended (29 bits, more than 4 hex digits)."""
    return len(str(can_id)) > 4
